package es.ubu.lsi.ubumonitorweb.data.dto

import es.ubu.lsi.ubumonitorweb.data.api.GradeItem

data class MoodleGradeItem(
  val id: Int,
  val itemname: String?,
  val itemtype: String,
  val itemmodule: String?,
  val iteminstance: Int,
  val itemnumber: Int?,
  val idnumber: String?,
  val categoryid: Int?,
  val outcomeid: Int?,
  val scaleid: Int?,
  val locked: Boolean?,
  val cmid: Int?,
  val weightraw: Double?,
  val weightformatted: String?,
  val status: String?,
  val graderaw: Double?,
  val gradedatesubmitted: Long?,
  val gradedategraded: Long?,
  val gradehiddenbydate: Boolean?,
  val gradeneedsupdate: Boolean?,
  val gradeishidden: Boolean?,
  val gradeislocked: Boolean?,
  val gradeisoverridden: Boolean?,
  val gradeformatted: String?,
  val grademin: Double?,
  val grademax: Double?,
  val rangeformatted: String?,
  val percentageformatted: String?,
  val feedback: String?,
  val feedbackformat: Int?,
) {
  fun toGradeItem() =
    GradeItem(
      id = id,
      cmid = cmid,
      name = itemname,
      type = itemtype,
      module = itemmodule,
      instance = iteminstance,
      number = itemnumber,
      category = categoryid,
      locked = locked == true,
      weight = weightraw,
      gradeRaw = graderaw,
      gradeMin = grademin,
      gradeMax = grademax,
      gradeLocked = gradeislocked == true,
      gradeHidden = gradeishidden == true,
      gradeOverridden = gradeisoverridden == true,
      gradeNeedsUpdate = gradeneedsupdate == true,
      gradeHiddenByDate = gradehiddenbydate == true,
      submittedMs = gradedatesubmitted?.times(1000),
      gradedMs = gradedategraded?.times(1000),
      status = status,
      feedback = feedback,
    )
}
